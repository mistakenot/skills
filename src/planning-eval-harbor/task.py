"""Compile a fixture into a Harbor task directory.

A Harbor task is "instruction + environment + test script". This module builds
one from a planning-eval fixture, in whichever of the two operator shapes was
asked for:

  * ``scripted`` — one Harbor *step* per operator message. Claude Code resumes
    its native session between steps (`resume_trajectory`), so the trial is a
    genuine multi-turn conversation with a deterministic operator: the message
    sent is the message in the fixture, byte for byte. This is the direct
    replacement for planning-eval's hand-scripted `human_turns`.

  * ``simulated`` — a single step whose instruction is the script, handed to a
    Harbor *user agent* (a second Claude Code) that relays it to the target
    over the ACP bridge. The operator is an LLM following a script, so what
    it actually sent has to be checked afterwards (`results.adherence`).

Either way the environment is the same: the target repo's tree at the start
SHA, minus its own `.claude/skills/` (the arm's skills are injected by Harbor,
so the two arms of a comparison differ only by workflow — the same boundary
`src/planning-eval/build.sh` draws), committed once so the agent sees a clean
`git log`. The test script exists because Harbor requires it; every job runs
with verification disabled, and if the script is ever executed it fails loudly
rather than inventing a reward.
"""

from __future__ import annotations

import shlex
import shutil
import subprocess
from dataclasses import dataclass
from pathlib import Path

from fixture import Fixture

SCRIPTED = "scripted"
SIMULATED = "simulated"
OPERATORS = (SCRIPTED, SIMULATED)

DOCKERFILE = """\
# Generated by src/planning-eval-harbor/task.py — do not edit; rebuilt every run.
FROM node:22-bookworm

# git/curl/python3 are what the planning skills shell out to; procps is what
# Harbor's own Claude Code install step expects. Node comes with the base image.
RUN apt-get update \\
 && apt-get install -y --no-install-recommends git curl ca-certificates python3 procps \\
 && apt-get clean

WORKDIR /app

# The target repo's tree at the fixture's start SHA (history-free, see task.py).
ADD repo.tar /app/

# One commit, carrying the original subject, so `git log` looks like a repo and
# not like eval scaffolding.
RUN git init -q \\
 && git add -A \\
 && git -c user.name=eval -c user.email=eval@local commit -q -m {subject}
"""

NO_VERIFIER_TEST = """\
#!/bin/bash
# planning-eval-harbor runs every job with verification disabled: judgement is a
# human reading the outputs, and there is no reward. Harbor requires this file to
# exist regardless. If it ever runs, something changed — fail rather than score.
echo "planning-eval-harbor: verifier invoked, but this harness has no verifier" >&2
exit 1
"""

REPLAY_PERSONA = """\
You are a replay operator, not a person with opinions. You have a fixed script
of messages and you send them verbatim, one at a time, in order. You never
improvise, never answer questions the coding agent asks you unless the script
says so, and never send a message that is not in the script. When the script is
exhausted, stop.
"""

SCRIPT_HEADER = """\
You are replaying a scripted conversation with the coding agent. Send it EXACTLY
the messages below, in order, one per `acpx prompt` call, verbatim — every line
between a message's markers, with no additions, paraphrase, trimming, or extra
messages. Wait for each reply before sending the next. After the last reply,
end your session. Do not write or edit files yourself.

Tip: for a multi-line message, write it to a file first and send it with
`acpx prompt -f <file>` so nothing is lost to shell quoting.
"""


@dataclass(frozen=True)
class BuiltTask:
    dir: Path
    operator: str
    messages: list[str]
    seed_tar: Path
    steps: list[str]

    @property
    def name(self) -> str:
        return self.dir.name


def step_name(i: int) -> str:
    """`turn-01`, `turn-02`, … — zero-padded so directory order is turn order."""
    return f"turn-{i:02d}"


def export_tree(repo: Path, sha: str, dest_tar: Path) -> None:
    """The repo's tree at `sha`, without history and without its own skills.

    History-free on purpose, for the same reasons `src/evals/scenarios/README.md`
    prefers a tarball to a clone: it is small, it is exactly reproducible from
    the sha, and there is no history for the agent to mine. The repo's own
    `.claude/skills/` is left out so the arm's injected skills are the only
    skills in play — the boundary planning-eval's build.sh draws by deleting
    the same directory. Project `CLAUDE.md` and the rest of `.claude/` stay:
    that is shared project context, not the variable under test.
    """
    subprocess.run(
        [
            "git", "-C", str(repo), "archive", "--format=tar", "-o", str(dest_tar),
            sha, "--", ".", ":(exclude).claude/skills",
        ],
        check=True,
        capture_output=True,
        text=True,
    )


def commit_subject(repo: Path, sha: str) -> str:
    out = subprocess.run(
        ["git", "-C", str(repo), "log", "-1", "--format=%s", sha],
        check=True, capture_output=True, text=True,
    )
    return out.stdout.strip() or f"start {sha[:12]}"


def render_script(messages: list[str]) -> str:
    """The simulated operator's instruction: the script, with unambiguous markers."""
    parts = [SCRIPT_HEADER]
    for i, msg in enumerate(messages, 1):
        parts.append(f"=== MESSAGE {i} of {len(messages)} ===\n{msg.rstrip()}\n=== END MESSAGE {i} ===\n")
    return "\n".join(parts)


def _task_toml(fx: Fixture, steps: list[str]) -> str:
    lines = [
        "# Generated by src/planning-eval-harbor/task.py — do not edit; rebuilt every run.",
        'schema_version = "1.4"',
        "",
        "[metadata]",
        f'source_fixture = "{fx.path}"',
        f'start_sha = "{fx.start_sha}"',
        f'arm = "{fx.arm_id}"',
        "",
        "[verifier]",
        "timeout_sec = 60.0",
        "",
        "[agent]",
        # Per step in a multi-step task, so this is planning-eval's per-turn cap.
        f"timeout_sec = {float(fx.limits.per_turn_timeout_s)}",
        "",
        "[environment]",
        "build_timeout_sec = 900.0",
    ]
    for name in steps:
        lines += ["", "[[steps]]", f'name = "{name}"']
    return "\n".join(lines) + "\n"


def build_task(fx: Fixture, out_root: Path, operator: str) -> BuiltTask:
    """Write `<out_root>/<fixture>-<arm>-<operator>/` and return what went in it.

    The directory is derived entirely from the fixture and is rebuilt on every
    run: the durable record of what ran is Harbor's own `lock.json` in the run
    directory (task digest, skill digests), not this scratch tree.
    """
    if operator not in OPERATORS:
        raise ValueError(f"operator must be one of {OPERATORS}, got {operator!r}")
    task_dir = out_root / f"{fx.id}-{fx.arm_id}-{operator}"
    if task_dir.exists():
        shutil.rmtree(task_dir)
    env_dir = task_dir / "environment"
    env_dir.mkdir(parents=True)

    seed_tar = env_dir / "repo.tar"
    export_tree(fx.target_repo, fx.start_sha, seed_tar)
    subject = commit_subject(fx.target_repo, fx.start_sha)
    (env_dir / "Dockerfile").write_text(DOCKERFILE.format(subject=shlex.quote(subject)))

    tests = task_dir / "tests"
    tests.mkdir()
    test_sh = tests / "test.sh"
    test_sh.write_text(NO_VERIFIER_TEST)
    test_sh.chmod(0o755)

    messages = fx.messages
    steps: list[str] = []
    if operator == SCRIPTED:
        for i, msg in enumerate(messages, 1):
            name = step_name(i)
            steps.append(name)
            step_dir = task_dir / "steps" / name
            step_dir.mkdir(parents=True)
            (step_dir / "instruction.md").write_text(msg.rstrip() + "\n")
    else:
        (task_dir / "instruction.md").write_text(render_script(messages))
        (task_dir / "persona.md").write_text((fx.persona or REPLAY_PERSONA).rstrip() + "\n")

    (task_dir / "task.toml").write_text(_task_toml(fx, steps))
    return BuiltTask(dir=task_dir, operator=operator, messages=messages, seed_tar=seed_tar, steps=steps)
